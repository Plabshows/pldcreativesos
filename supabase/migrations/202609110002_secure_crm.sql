-- Protect the last administrator and organisation membership from reassignment.
create or replace function public.protect_membership() returns trigger language plpgsql
security definer set search_path=public,pg_temp as $$
begin
  perform 1 from public.organizations where id=old.organization_id for update;
  if tg_op='UPDATE' and (new.organization_id<>old.organization_id or new.user_id<>old.user_id) then raise exception 'La identidad de un miembro no se puede cambiar.'; end if;
  if old.role='admin' and (tg_op='DELETE' or new.role<>'admin') and
    (select count(*) from public.organization_members where organization_id=old.organization_id and role='admin')<=1
    then raise exception 'El equipo necesita al menos un administrador.'; end if;
  if tg_op='DELETE' then return old; end if; return new;
end; $$;
create trigger protect_member before update or delete on public.organization_members for each row execute function public.protect_membership();

