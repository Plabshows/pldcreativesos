-- All references are checked against the row's organisation, including owners.
create or replace function public.enforce_tenant_references() returns trigger language plpgsql
security definer set search_path=public,pg_temp as $$
declare fk record; target uuid; row_org uuid; target_org uuid; begin
  row_org := (to_jsonb(new)->>'organization_id')::uuid;
  if tg_op='UPDATE' and row_org <> (to_jsonb(old)->>'organization_id')::uuid then
    raise exception 'No se puede cambiar la organización de un registro.';
  end if;
  for fk in
    select a.attname as col, c.confrelid::regclass as target_table, c.confrelid as target_oid
    from pg_constraint c join pg_attribute a on a.attrelid=c.conrelid and a.attnum=c.conkey[1]
    where c.contype='f' and c.conrelid=tg_relid and array_length(c.conkey,1)=1
  loop
    target := (to_jsonb(new)->>fk.col)::uuid;
    if target is null or fk.target_table='public.organizations'::regclass then continue; end if;
    if fk.target_table='public.users'::regclass then
      if not exists(select 1 from public.organization_members where organization_id=row_org and user_id=target) then
        raise exception 'La persona responsable no pertenece al equipo.';
      end if;
    elsif exists(select 1 from pg_attribute where attrelid=fk.target_oid and attname='organization_id' and not attisdropped) then
      execute format('select organization_id from %s where id=$1',fk.target_table) into target_org using target;
      if target_org is distinct from row_org then raise exception 'La relación no pertenece a esta organización.'; end if;
    end if;
  end loop;
  return new;
end; $$;

-- Audit is generated by the database, never by trusting a caller-supplied actor.
create or replace function public.audit_business_change() returns trigger language plpgsql
security definer set search_path=public,pg_temp as $$
begin
  insert into public.activity_log(organization_id,actor_id,entity_type,entity_id,action,before_data,after_data)
    values(new.organization_id,auth.uid(),tg_table_name,new.id,tg_op,
      case when tg_op='UPDATE' then to_jsonb(old) else null end,to_jsonb(new));
  return new;
end; $$;

do $$ declare t text; begin
  foreach t in array array['clients','client_contacts','leads','events','event_requirements','event_financials','talent','talent_disciplines','talent_rates','talent_media','event_talent','suppliers','concepts','storage_locations','assets','asset_movements','proposals','proposal_options','proposal_items','tasks','payments','communications','notes','files','pricing_rules'] loop
    execute format('create trigger enforce_tenant before insert or update on public.%I for each row execute function public.enforce_tenant_references()',t);
