-- Restrict the initial schema before it is used with business data.
create or replace function public.has_org_role(target_org uuid, permitted text[]) returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select exists(select 1 from public.organization_members
    where organization_id=target_org and user_id=auth.uid() and role::text=any(permitted));
$$;
revoke all on function public.has_org_role(uuid,text[]) from public;
grant execute on function public.has_org_role(uuid,text[]) to authenticated;

do $$ declare p record; t text; roles text[]; begin
  for p in select tablename,policyname from pg_policies where schemaname='public' and tablename not in ('organizations','users','organization_members') loop
    execute format('drop policy %I on public.%I',p.policyname,p.tablename);
  end loop;
  foreach t in array array['clients','client_contacts','leads','events','event_requirements','event_financials','talent','talent_disciplines','talent_rates','talent_media','event_talent','suppliers','concepts','storage_locations','assets','asset_movements','proposals','proposal_options','proposal_items','tasks','payments','communications','notes','files','pricing_rules','activity_log','ai_activity'] loop
    roles := case
      when t in ('activity_log','ai_activity','payments') then array['admin']
      when t in ('event_financials','talent','talent_disciplines','talent_rates','talent_media','suppliers','event_talent') then array['admin','producer']
      when t in ('assets','asset_movements','storage_locations','event_requirements','events') then array['admin','producer','wardrobe']
      else array['admin','producer','sales'] end;
    execute format('create policy role_read on public.%I for select to authenticated using (public.has_org_role(organization_id,%L::text[]))',t,roles);
    if t in ('activity_log','ai_activity') then continue; end if;
    if t='pricing_rules' then roles:=array['admin']; end if;
    if t='events' then roles:=array['admin','producer']; end if;
    execute format('create policy role_insert on public.%I for insert to authenticated with check (public.has_org_role(organization_id,%L::text[]))',t,roles);
    execute format('create policy role_update on public.%I for update to authenticated using (public.has_org_role(organization_id,%L::text[])) with check (public.has_org_role(organization_id,%L::text[]))',t,roles,roles);
    -- No hard deletion of business rows from application sessions.
  end loop;
end $$;

