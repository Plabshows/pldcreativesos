create or replace function public.prepare_confirmed_event() returns trigger language plpgsql
security definer set search_path=public,pg_temp as $$
declare item text; begin
  if new.status not in ('confirmed','production') or new.deleted_at is not null then return new; end if;
  foreach item in array array['Confirmar artistas','Preparar vestuario','Confirmar horarios con el cliente'] loop
    insert into public.tasks(organization_id,title,event_id,owner_id,priority,automation_key)
    values(new.organization_id,item,new.id,new.owner_id,'high',item)
    on conflict(event_id,automation_key) where automation_key is not null do nothing;
  end loop;
  return new;
end; $$;
create trigger event_production_tasks after insert or update of status on public.events
for each row execute function public.prepare_confirmed_event();

